const MONTHS = Object.keys(MONTHLY_EUR_OZ).sort();

/** Cours moyen du mois de la date (le dernier mois connu au-delà, le premier avant). */
export function monthlyEurOz(date: Date): Record<Metal, number> {
  const key = `${date.getFullYear()}-${String(date.getMonth() + 1).padStart(2, '0')}`;
  const k = MONTHLY_EUR_OZ[key] ? key : key < MONTHS[0] ? MONTHS[0] : MONTHS[MONTHS.length - 1];
  const [gold, silver, platinum] = MONTHLY_EUR_OZ[k];
  return { gold, silver, platinum };
}
